# -*- coding: utf-8 -*-
r"""生成 / 校验结果工件的 SHA-256 清单。

外审（第七轮）要求主 JSON 输出附密码学散列，以支持逐位可复现性核对。
本脚本把 src/*.py 与 results/*.json 的 SHA-256 写入仓库根的 MANIFEST.sha256。

用法：
    python src/make_manifest.py            # 重新生成 MANIFEST.sha256
    python src/make_manifest.py --verify   # 按现有清单校验，返回码 0=全同、1=有差异

格式与 sha256sum(1) 兼容：`<hex>  <相对路径>`（相对仓库根，正斜杠）。
注意：任何一次重跑若改写了 results/*.json，须重跑本脚本更新清单；
清单在发布前应作为最后一步重新生成。
"""
import hashlib
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
MANIFEST = os.path.join(ROOT, "MANIFEST.sha256")

# 收录范围：脚本 + 机器可读结果。按相对路径排序，保证可复现的清单顺序。
INCLUDE_DIRS = ("src", "results")
EXCLUDE_NAMES = {"__pycache__", "make_manifest.py"}


def iter_files():
    for d in INCLUDE_DIRS:
        base = os.path.join(ROOT, d)
        for name in sorted(os.listdir(base)):
            if name in EXCLUDE_NAMES or name.startswith("."):
                continue
            p = os.path.join(base, name)
            if os.path.isfile(p) and (name.endswith(".py") or name.endswith(".json")
                                      or name.endswith(".lean")):
                yield os.path.relpath(p, ROOT).replace(os.sep, "/"), p


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def build():
    lines = []
    for rel, p in iter_files():
        lines.append("%s  %s" % (sha256_of(p), rel))
    return lines


def main():
    verify = "--verify" in sys.argv
    lines = build()
    if verify:
        if not os.path.exists(MANIFEST):
            print("FAIL: 清单不存在:", MANIFEST)
            return 1
        recorded = {}
        with io.open(MANIFEST, "r", encoding="utf-8") as f:
            for ln in f:
                ln = ln.strip()
                if not ln or ln.startswith("#"):
                    continue
                h, rel = ln.split(None, 1)
                recorded[rel.strip()] = h
        bad = 0
        for ln in lines:
            h, rel = ln.split(None, 1)
            if recorded.get(rel) != h:
                print("MISMATCH:", rel, "清单", recorded.get(rel), "实际", h)
                bad += 1
        extra = set(recorded) - {ln.split(None, 1)[1] for ln in lines}
        for rel in sorted(extra):
            print("STALE(清单有、磁盘无):", rel)
            bad += 1
        print("校验:", "全同" if bad == 0 else "%d 处不一致" % bad, "共", len(lines), "个文件")
        return 0 if bad == 0 else 1
    with io.open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        f.write("# SHA-256 of reproduction artifacts (scripts + machine-readable results)\n")
        f.write("# generated by src/make_manifest.py -- regenerate after any re-run\n")
        f.write("\n".join(lines) + "\n")
    print("写出:", MANIFEST, " 共", len(lines), "个文件")
    for ln in lines:
        print(" ", ln)


if __name__ == "__main__":
    sys.exit(main())
